"""Multi-seed summary for the controlled B vs C experiment (from run artifacts only).

    python -m reports.seeds --runs-dir artifacts/models --prefix v2 --out ../experiments/reports/seeds.md

For every `model-{b,c}-<prefix>-s<seed>` run with a summary.json it reports the selected
(best-epoch) proxy metrics, then per seed the paired difference C - B, and the mean and
sample standard deviation over seeds. The trainer's per-epoch proxy numbers were checked to
equal `evaluation.proxy_eval` on the same checkpoints (v1: 0.9743 / 0.9769), so no
re-encoding is needed. Proxy = generated validation queries, NOT human judgments.
"""

from __future__ import annotations

import argparse
import json
import re
import statistics
import sys
from pathlib import Path

METRICS = ("recall@5", "mrr@10", "ndcg@10")


def collect(runs_dir: Path, prefix: str) -> dict[str, dict[int, dict]]:
    out: dict[str, dict[int, dict]] = {"b": {}, "c": {}}
    pattern = re.compile(rf"^model-([bc])-{re.escape(prefix)}-s(\d+)$")
    for run in sorted(runs_dir.iterdir()):
        match = pattern.match(run.name)
        if not match or not (run / "summary.json").is_file():
            continue
        summary = json.loads((run / "summary.json").read_text("utf-8"))
        history = json.loads((run / "history.json").read_text("utf-8"))
        best = next(e for e in history["epochs"] if e["epoch"] == summary["best_epoch"])
        out[match.group(1)][int(match.group(2))] = {
            "run": run.name, "best_epoch": summary["best_epoch"],
            "epochs_run": summary["epochs_run"], "seconds": summary.get("wall_clock_seconds"),
            **{m: best["proxy"][m] for m in METRICS}}
    return out


def _fmt(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.4f}"


def render(data: dict[str, dict[int, dict]], prefix: str) -> str:
    lines = [f"# Multi-seed B vs C ({prefix}) - PROXY (generated validation queries)", "",
             "Generated by `python -m reports.seeds`; values are the selected (best-epoch) "
             "checkpoint's proxy metrics from each run's history.json.", "",
             "| model | seed | run | best epoch / run | Recall@5 | MRR@10 | nDCG@10 | seconds |",
             "|---|---:|---|---|---:|---:|---:|---:|"]
    for model in ("b", "c"):
        for seed, r in sorted(data[model].items()):
            lines.append(f"| {model.upper()} | {seed} | {r['run']} | {r['best_epoch']} / {r['epochs_run']} | "
                         f"{r['recall@5']:.4f} | {r['mrr@10']:.4f} | {r['ndcg@10']:.4f} | {r['seconds']} |")
    seeds = sorted(set(data["b"]) & set(data["c"]))
    lines += ["", f"Paired seeds with both runs finished: {seeds or 'none'}", ""]
    if seeds:
        lines += ["| metric | mean B | sd B | mean C | sd C | per-seed C - B | mean C - B | sd(C - B) |",
                  "|---|---:|---:|---:|---:|---|---:|---:|"]
        for m in METRICS:
            b = [data["b"][s][m] for s in seeds]
            c = [data["c"][s][m] for s in seeds]
            d = [y - x for x, y in zip(b, c)]
            sd = (lambda v: statistics.stdev(v) if len(v) > 1 else None)  # noqa: E731
            lines.append(f"| {m} | {statistics.mean(b):.4f} | {_fmt(sd(b))} | {statistics.mean(c):.4f} | "
                         f"{_fmt(sd(c))} | {', '.join(f'{x:+.4f}' for x in d)} | "
                         f"{statistics.mean(d):+.4f} | {_fmt(sd(d))} |")
        lines += ["", "With 3 seeds, a mean difference smaller than about two standard deviations "
                  "of (C - B) is not evidence of an effect; the proxy itself is near its ceiling."]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Multi-seed B vs C summary from run artifacts.")
    parser.add_argument("--runs-dir", type=Path, default=Path("artifacts/models"))
    parser.add_argument("--prefix", default="v2")
    parser.add_argument("--out", type=Path)
    args = parser.parse_args(argv)
    text = render(collect(args.runs_dir, args.prefix), args.prefix)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text, "utf-8")
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
